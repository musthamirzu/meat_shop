import mongoose from "mongoose";

const preparationTypeSchema = new mongoose.Schema(
  {
    shopId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Shop",
      required: true,
      index: true,
    },

    name: {
      type: String,
      required: true,
      trim: true,
    },

    slug: {
      type: String,
      required: true,
      lowercase: true,
      trim: true,
    },

    description: {
      type: String,
      default: "",
      trim: true,
    },

    image: {
      type: String,
      default: "",
    },

    sortOrder: {
      type: Number,
      default: 0,
    },

    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);


preparationTypeSchema.index(
  {
    shopId: 1,
    slug: 1,
  },
  {
    unique: true,
  }
);


const PreparationType = mongoose.model(
  "PreparationType",
  preparationTypeSchema
);

export default PreparationType;